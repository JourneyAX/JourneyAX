/**
 * How a sample connector's seed file and README are written. Shared by build-seeds.ts (the full build) and extend-seeds.ts (the stages applied
 * to the committed seeds), so both give the same bytes. Nothing here reads or builds data.
 */
import type { ConnectorFile, SeedFile } from '../src/types';

export function seedText(seed: SeedFile): string {
  const blocks = Object.entries(seed.collections).map(([name, rows]) => `    ${JSON.stringify(name)}: [\n${rows.map((row) => `      ${JSON.stringify(row)}`).join(',\n')}\n    ]`);
  return `{\n  "connectorId": ${JSON.stringify(seed.connectorId)},\n  "tenantId": ${JSON.stringify(seed.tenantId)},\n  "builtFrom": ${JSON.stringify(seed.builtFrom)},\n  "provenance": ${JSON.stringify(seed.provenance, null, 2).replace(/\n/g, '\n  ')},\n  "collections": {\n${blocks.join(',\n')}\n  }\n}\n`;
}

export function readme(definition: ConnectorFile, seed: SeedFile): string {
  const rows = Object.entries(seed.collections).map(([name, records]) => {
    const p = seed.provenance[name];
    const sampleCount = records.filter((record) => record.sample === true).length;
    return `| \`${name}\` | ${records.length} | ${p.origin === 'real' ? 'real' : p.origin === 'sample' ? 'made up' : 'real and made up'} | ${sampleCount}/${records.length} | ${p.realFields.join(', ') || '-'} | ${p.madeUpFields.join(', ') || '-'} |`;
  });
  return [
    `# ${definition.title}`, '',
    `Stands in for: **${definition.standsInFor}**.`, '',
    `${definition.description} This is **sample data**: a stand-in that speaks MCP at \`POST /mcp/${definition.connectorId}\`. Generated by \`scripts/build-seeds.ts\`; do not edit by hand.`, '',
    '## Records', '',
    '| Collection | Records | Origin | Marked `sample: true` | Real fields (copied from the PlaceMakers data) | Made-up fields |',
    '|---|---|---|---|---|---|', ...rows, '',
    `Smallest allowed per collection (a test checks it): ${Object.entries(definition.minimums).map(([k, v]) => `${k} ${v}`).join(', ')}.`, '',
    '## Tools', '',
    ...definition.tools.map((tool) => `- \`${tool.name}\`${tool.annotations?.readOnlyHint === false ? ' (changes data, so it asks first)' : ''}: ${tool.description}`), '',
    'Records that are invented, or that mix real and invented values, carry `sample: true`. The people, trade businesses, customer phone numbers and email addresses are made up (emails end in `.test`); any resemblance to a real person or business is chance. Branch names, codes and phone numbers are the ones the PlaceMakers store locator page lists. No customer data was read.', '',
  ].join('\n');
}
